-- Emil Tagebuch uses a dedicated table in the existing Wildora Supabase project.
-- Run once in Supabase SQL Editor if the database migration has not already been applied.
create table if not exists public.diary_entries (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  excerpt text not null default '' check (char_length(excerpt) <= 180),
  body text not null,
  image_url text,
  created_at timestamptz not null default now()
);
alter table public.diary_entries enable row level security;
grant select on public.diary_entries to anon, authenticated;
grant insert, update, delete on public.diary_entries to authenticated;
grant usage, select on sequence public.diary_entries_id_seq to authenticated;

drop policy if exists "Public can read diary" on public.diary_entries;
create policy "Public can read diary" on public.diary_entries
for select to anon, authenticated using (true);

